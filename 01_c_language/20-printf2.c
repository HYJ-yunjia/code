#include <stdio.h>

int main(int argc, char const *argv[])
{
    //宽度
    int a = 557;
    printf("a = %d\n",a);//按照十进制输出整数
    printf("a = %8d\n",a);//按照十进制输出整数，输出宽度8个位置，不够在左补空格
    printf("a = %2d\n",a);//按照十进制输出整数，输出宽度2个位置，超出设置的位置，按照实际输出
    printf("str = %8s\n","goodbye");//输出一个字符串输出宽度8个位置，不够在左补一个空格
    printf("str = %4s\n","goodbye");//输出一个字符串输出宽度4个位置，超出设置的位置，按照实际输出

    //.n对于实数，保留小数点后面的有效位数
    float b = 456.789;
    printf("b=%f",b);//输出一个实数小数点后保留后6位
    printf("b=%.2f",b);//输出一个实数，小数点后保留后2位，四舍五入
    printf("b=%.0f",b);//输出一个实数，小数点后保留后0位，四舍五入
    printf("b=%8.2f",b);//输出一个实数，宽度是8，不够左补空格，小数点后保留后2位，四舍五入
    printf("b=%4.2f",b);//输出一个实数，宽度是4，超出设置位置，按照实际输出，小数点后保留后2位，四舍五入

    //.n对于字符串，控制字符串输出的个数
    printf("b=%s\n","goodbye");//输出一个字符串
    printf("b=%.3s\n","goodbye");//输出一个字符串，字符串有效输出字符是goo
    printf("b=%8.3s\n","goodbye");//输出一个字符串，字符串有效输出字符是goo，宽度是8，不够左补空格
    printf("b=%3.3s\n","goodbye");//输出一个字符串，字符串有效输出字符是goo，超出设置位置，按照实际输出

    //# 
    printf("a=%o\n",a);//按照八进制输出整数
    printf("a=%#o\n",a);//按照八进制输出整数，会在输出时，加上0的前缀（表示八进制）
    printf("a=%#x\n",a);//按照十六进制输出整数，会在输出时，加上0x的前缀
    printf("a=%#X\n",a);//按照十六进制输出整数，会在输出时，加上0X的前缀

    //+
    printf("a=%+d\n",a);//按照十进制输出整数，带上符号位，正数+负数-
    a=-123;
    printf("a=%d\n",a);//按照十进制输出整数
    
    //-左对齐，系统默认是右对齐
    printf("str = %8s\n","goodbye");//右对齐，左补一个空格
    printf("str = %-8s\n","goodbye");//左对齐，右补一个空格
    printf("a=%8d\n",a);//默认右对齐，左补四个空格
    printf("a=%-8d\n",a);//默认左对齐，右补四个空格

    //0 左补0，不补空格只限于右对齐时使用，左对齐补0会产生逻辑错误（100如果补0会变成10000）
    //0和-不能同时出现
    printf("a=%08d\n",a);//右对齐，左补四个0
    printf("a=%-08d\n",a);//编译不报错，会自动忽略0的作用

    printf("a=%ld\n",a);//long类型
    printf("b=%lf\n",b);//double类型

    return 0;
}
